def targets():
    """Mean colour of each of the build's texture images, by name (groundcover's and roadtex's)."""
    with tempfile.TemporaryDirectory() as folder:
        groundcover.make_textures(folder)
        roadtex.make_surfaces(folder)
        return {f[:-4]: np.asarray(Image.open(os.path.join(folder, f)).convert("RGB"), float).reshape(-1, 3).mean(0)
                for f in os.listdir(folder) if f.endswith(".png")}


def target_of(name, means):
    """The colour name's material is matched to: its build look's mean, a given RGB, or a mixture's half and half. Pure."""
    look = LOOKS[name]
    if look.mix:
        return (target_of(look.mix[0], means) + target_of(look.mix[1], means)) / 2
    return np.asarray(means[look.target] if isinstance(look.target, str) else look.target, float)


def _painted(name, means, px, density, seed):
    """(colour matched, height) of name, mixtures painted from their two halves."""
    look = LOOKS[name]
    rng = np.random.default_rng(seed)
    if not look.mix:
        p = Painter(look.metres, px, rng, density)
        look.paint(p)
        colour, height = p.finish()
        return matched(colour, target_of(name, means)), height
    first, second, how = look.mix
    a, b = _painted(first, means, px, density, seed + 1), _painted(second, means, px, density, seed + 2)
    cover = 0.5 + 0.5 * fbm(px, look.metres / 1.2, 4, rng)
    if how == "hollows":                                # snow fills what lies low in the other first
        cover = cover + 0.9 * (0.5 - b[1])
    edge = np.clip((cover - 0.5) / 0.08 + 0.5, 0, 1)    # (soft over a few centimetres, not a blur)
    colour, height = blend(a, b, edge)
    # (each half has its own build colour; the mixture keeps half of each, its mean nudged onto their middle)
    return matched(colour, target_of(name, means)), height


def paint(name, means, px=PX, density=1.0, seed=7):
    """The maps of name: colour (RGB), normal (RGB, +Y) and roughness (L), each px square and seamless."""
    look = LOOKS[name]
    colour, height = _painted(name, means, px, density, seed)
    return colour, normal_map(height, look.normals * px / 1024), roughness_map(height, *look.rough)


JPEG_QUALITY = 92          # (every look: 75 MiB instead of 177 as PNG; a few levels off on average, in the fine blades)


def encoded(image):
    """image as the library keeps it: a JPEG, full chroma (a normal map's channels are directions, not colour). Pure."""
    out = io.BytesIO()
    image.save(out, "JPEG", quality=JPEG_QUALITY, subsampling=0)
    return out.getvalue()


def add_to_library(name, maps):
    """name's three maps as a material of library/ (the curated library build_library.py ships from); its result."""
    from app import materiallibrary
    look = LOOKS[name]
    prepared = {role: materiallibrary.prepare(f"{name}_{role}.jpg", encoded(image), role)
                for role, image in zip(("colour", "normal", "roughness"), maps)}
    return materiallibrary.add({
        "token": prepared["colour"]["token"], "filename": prepared["colour"]["filename"], "name": look.name, "category": look.category,
        "repeat": [float(look.metres)] * 2, "variation": True, "source": "tools/painted_ground.py", "license": LICENSE,
        "tags": ["Map2Lap", "CC0", "painted", name],
        "maps": {role: {"token": prepared[role]["token"], "filename": prepared[role]["filename"]} for role in ("normal", "roughness")}})


def contact_sheet(made, path, side=256):
    """Every colour map small, with its name, in one picture."""
    names = list(made)
    cols = 6
    rows = math.ceil(len(names) / cols)
    sheet = Image.new("RGB", (cols * side, rows * (side + 18)), (24, 24, 24))
    d = ImageDraw.Draw(sheet)
    for k, name in enumerate(names):
        x, y = (k % cols) * side, (k // cols) * (side + 18)
        sheet.paste(made[name].resize((side, side), Image.LANCZOS), (x, y + 18))
        d.text((x + 4, y + 3), name, fill=(230, 230, 230))
    sheet.save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", required=True, help="folder for the PNGs and contact.png")
    parser.add_argument("--only", help="comma-separated names of LOOKS")
    parser.add_argument("--import", dest="into", action="store_true", help="also add them to library/")
    parser.add_argument("--px", type=int, default=PX)
    args = parser.parse_args()
    names = args.only.split(",") if args.only else list(LOOKS)
    os.makedirs(args.out, exist_ok=True)
    means, made = targets(), {}
    for name in names:
        maps = paint(name, means, px=args.px)
        for role, image in zip(("colour", "normal", "roughness"), maps):
            image.save(os.path.join(args.out, f"{name}_{role}.png"))
        made[name] = maps[0]
        if args.into:
            result = add_to_library(name, maps)
            print(f"{name}: {result['material']['name']} {'(already there)' if result['duplicate'] else 'added'}")
