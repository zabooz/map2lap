@dataclass
class Look:
    """A material to paint: its name in the library, category, metres per repeat, how it is painted, the build's look whose
    colour it takes (target: a groundcover/roadtex texture's name or an RGB), how strong its normals are, its roughness."""
    name: str
    category: str
    metres: float
    paint: Callable
    target: object
    normals: float = 6.0
    rough: tuple = (0.92, 0.18)
    mix: tuple = ()                 # (two looks' names and how the first lies on the second: "patches" or "hollows")


def _l(name, category, metres, paint, target, **kw):
    return Look(name + " (painted)", category, metres, paint, target, **kw)


