# --- noise ---

def periodic_noise(size, cells, rng):
    """Smooth value noise in [-1, 1] over size pixels that repeats with them, cells grid cells per repeat. Pure but for rng."""
    cells = max(1, int(cells))
    grid = rng.uniform(-1, 1, (cells, cells))
    t = np.arange(size) / size * cells
    i = np.floor(t).astype(int)
    f = t - i
    f = f * f * (3 - 2 * f)
    i0, i1 = i % cells, (i + 1) % cells
    a = grid[i0][:, i0] * (1 - f)[None, :] + grid[i0][:, i1] * f[None, :]
    b = grid[i1][:, i0] * (1 - f)[None, :] + grid[i1][:, i1] * f[None, :]
    return a * (1 - f)[:, None] + b * f[:, None]


def fbm(size, cells, octaves, rng):
    """Octaves of periodic noise, roughly in [-1, 1]."""
    out, amp, total = np.zeros((size, size)), 1.0, 0.0
    for k in range(octaves):
        out += amp * periodic_noise(size, cells * 2 ** k, rng)
        total += amp
        amp *= 0.5
    return out / total


def _rgb(c):
    return tuple(int(round(v)) for v in c)


def _scaled(c, f):
    return _rgb(np.clip(np.asarray(c, float) * f, 0, 255))


