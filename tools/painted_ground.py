class Painter:
    """A square of metres being painted: colour and height at SS times px, every shape continued over the edges.
    density: a share of every count (tests paint thin)."""

    def __init__(self, metres, px, rng, density=1.0):
        self.metres, self.px, self.rng, self.density = metres, px, rng, density
        self.n = px * SS
        self.k = self.n / metres                      # pixels per metre
        self.colour = Image.new("RGB", (self.n, self.n), (128, 128, 128))
        self.height = Image.new("L", (self.n, self.n), 80)
        self.clumps = np.zeros((self.n, self.n))
        self.patches = np.zeros((self.n, self.n))
        self._draws()

    def _draws(self):
        self.dc, self.dh = ImageDraw.Draw(self.colour), ImageDraw.Draw(self.height)

    def count(self, per_m2):
        return int(per_m2 * self.metres ** 2 * self.density)

    def m(self, metres):
        """metres in drawn pixels."""
        return metres * self.k

    def points(self, count, at=None):
        """count places: uniform, or where at(x, y) (arrays of pixels) says True."""
        xs, ys = self.rng.uniform(0, self.n, count), self.rng.uniform(0, self.n, count)
        if at is not None:
            keep = at(xs, ys)
            xs, ys = xs[keep], ys[keep]
        return xs, ys

    def shape(self, kind, pts, colour, height=None, width=0):
        """One shape (ImageDraw's polygon, ellipse, line, rectangle) and its copies over the edges it crosses."""
        margin = width + 2
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        ox = [0] + ([self.n] if min(xs) - margin < 0 else []) + ([-self.n] if max(xs) + margin >= self.n else [])
        oy = [0] + ([self.n] if min(ys) - margin < 0 else []) + ([-self.n] if max(ys) + margin >= self.n else [])
        extra = {"width": max(1, int(width))} if kind == "line" else {}
        for dx in ox:
            for dy in oy:
                moved = [(x + dx, y + dy) for x, y in pts]
                getattr(self.dc, kind)(moved, fill=colour, **extra)
                if height is not None:
                    getattr(self.dh, kind)(moved, fill=int(height), **extra)

    def _at(self, x, y):
        return int(y) % self.n, int(x) % self.n

    # (the ground under everything)
    def ground(self, dark, light, clump_m=0.5, patch_m=3.0, tint=10.0, heights=(10, 90), octaves=4):
        """A base from dark to light by clumps of clump_m, warmer or cooler over patches of patch_m."""
        rng, n = self.rng, self.n
        self.clumps = fbm(n, self.metres / clump_m, octaves, rng)
        self.patches = fbm(n, self.metres / patch_m, 2, rng)
        shade = np.clip(0.5 + 0.5 * self.clumps, 0, 1)
        base = np.stack([np.interp(shade, [0, 1], [dark[k], light[k]]) for k in range(3)], -1)
        base[..., 0] += tint * self.patches
        base[..., 2] -= 0.6 * tint * self.patches
        self.colour = Image.fromarray(np.clip(base, 0, 255).astype(np.uint8))
        self.height = Image.fromarray(np.interp(shade, [0, 1], heights).astype(np.uint8))
        self._draws()

    def bands(self, count, strength, wobble_m=0.0, vertical=False, ridges=0):
        """Alternate count stripes lighter and darker by strength (mown lawn, field rows); ridges: their height apart."""
        a = np.asarray(self.colour, float)
        h = np.asarray(self.height, float)
        y = np.arange(self.n)[:, None] + self.m(wobble_m) * np.sin(np.arange(self.n)[None, :] / self.n * 2 * math.pi * 3)
        wave = np.sin(y / self.n * count * math.pi * 2)
        side = np.tanh(3 * wave)
        if vertical:
            side, wave = side.T, wave.T
        a *= (1 + strength * side)[..., None]
        h += ridges * wave
        self.colour = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))
        self.height = Image.fromarray(np.clip(h, 0, 255).astype(np.uint8))
        self._draws()

    def row_at(self, count, half_m):
        """A placement rule: within half_m of the middle of one of count rows across the square."""
        spacing = self.n / count
        return lambda xs, ys: np.abs((ys % spacing) - spacing / 2) < self.m(half_m)

    # (what lies on it)
    def blades(self, per_m2, length_m, width_m, dark, light, angle=None, jitter=math.pi, at=None, heights=(110, 250)):
        """Grass seen from above: strokes dark at the foot, light at the tip; longer and lighter on top of a clump."""
        xs, ys = self.points(self.count(per_m2), at)
        for x, y in zip(xs, ys):
            top = 0.5 + 0.5 * self.clumps[self._at(x, y)]
            lean = (angle if angle is not None else 0.0) + self.rng.uniform(-jitter, jitter)
            length = self.m(self.rng.uniform(*length_m)) * (0.7 + 0.6 * top)
            tip = (x + math.cos(lean) * length, y + math.sin(lean) * length)
            mid = ((x + tip[0]) / 2, (y + tip[1]) / 2)
            width = max(1.0, self.m(self.rng.uniform(*width_m)))
            foot = dark[self.rng.integers(len(dark))]
            pick = min(len(light) - 1, max(0, int(top * len(light) + self.rng.uniform(-1, 1))))
            shift = self.patches[self._at(x, y)]
            tipc = _rgb(np.asarray(light[pick], float) + 12 * shift * np.array([1, 0.6, -0.5]))
            self.shape("line", [(x, y), mid], _rgb(foot), heights[0] + 40 * top, width + 1)
            self.shape("line", [mid, tip], tipc, heights[1] - 60 * (1 - top), width)

    def strokes(self, per_m2, length_m, width_m, colours, height, angle=None, jitter=math.pi, at=None):
        """Straight strokes of one colour each: needles, twigs, straw, cracks."""
        xs, ys = self.points(self.count(per_m2), at)
        for x, y in zip(xs, ys):
            a = (angle if angle is not None else 0.0) + self.rng.uniform(-jitter, jitter)
            length = self.m(self.rng.uniform(*length_m))
            end = (x + math.cos(a) * length, y + math.sin(a) * length)
            self.shape("line", [(x, y), end], _rgb(colours[self.rng.integers(len(colours))]), height,
                       max(1.0, self.m(self.rng.uniform(*width_m))))

    def specks(self, per_m2, radius_m, colours, height=None, at=None):
        """Round specks: grains, crumbs, moss, granules."""
        xs, ys = self.points(self.count(per_m2), at)
        for x, y in zip(xs, ys):
            r = max(0.6, self.m(self.rng.uniform(*radius_m)))
            self.shape("ellipse", [(x - r, y - r), (x + r, y + r)], _rgb(colours[self.rng.integers(len(colours))]), height)

    def pebbles(self, per_m2, radius_m, colours, at=None, heights=(140, 235), flat=0.75):
        """Stones lit from the north-west: a shadow to the south-east, the stone, a highlight; their middle high."""
        xs, ys = self.points(self.count(per_m2), at)
        for x, y in zip(xs, ys):
            r = max(1.0, self.m(self.rng.uniform(*radius_m)))
            ry = r * self.rng.uniform(flat, 1.0)
            c = np.asarray(colours[self.rng.integers(len(colours))], float)
            self.shape("ellipse", [(x - r + 0.3 * r, y - ry + 0.35 * ry), (x + r + 0.3 * r, y + ry + 0.35 * ry)], _scaled(c, 0.55), heights[0] * 0.6)
            self.shape("ellipse", [(x - r, y - ry), (x + r, y + ry)], _rgb(c), heights[0])
            self.shape("ellipse", [(x - 0.55 * r, y - 0.6 * ry), (x + 0.35 * r, y + 0.25 * ry)], _scaled(c, 1.12), heights[1])

    def soil(self, per_m2, radius_m, colours, below=-0.35):
        """Bare earth between tufts, where the clumps are thinnest (below: their value under which)."""
        xs, ys = self.points(self.count(per_m2), lambda x, y: self.clumps[y.astype(int), x.astype(int)] < below)
        for x, y in zip(xs, ys):
            r = max(1.0, self.m(self.rng.uniform(*radius_m)))
            self.shape("ellipse", [(x - r, y - 0.7 * r), (x + r, y + 0.7 * r)], _rgb(colours[self.rng.integers(len(colours))]), 12)

    def leaves(self, per_m2, length_m, colours, at=None):
        """Fallen leaves: pointed ovals in any direction, a darker vein."""
        xs, ys = self.points(self.count(per_m2), at)
        for x, y in zip(xs, ys):
            a, length = self.rng.uniform(0, 2 * math.pi), self.m(self.rng.uniform(*length_m))
            w = length * self.rng.uniform(0.3, 0.45)
            c = colours[self.rng.integers(len(colours))]
            pts = []
            for t in np.linspace(0, 2 * math.pi, 10, endpoint=False):
                u, v = 0.5 * length * math.cos(t), 0.5 * w * math.sin(t) * (1 - 0.35 * math.cos(t))
                pts.append((x + u * math.cos(a) - v * math.sin(a), y + u * math.sin(a) + v * math.cos(a)))
            self.shape("polygon", pts, _rgb(c), self.rng.uniform(120, 200))
            self.shape("line", [(x - 0.4 * length * math.cos(a), y - 0.4 * length * math.sin(a)),
                                (x + 0.4 * length * math.cos(a), y + 0.4 * length * math.sin(a))], _scaled(c, 0.75), None, 1)

    def flowers(self, per_m2, colours, size_m=(0.006, 0.01)):
        """Small flowers: five petals round a darker heart."""
        xs, ys = self.points(self.count(per_m2))
        for x, y in zip(xs, ys):
            s = self.m(self.rng.uniform(*size_m))
            petal = _rgb(colours[self.rng.integers(len(colours))])
            for k in range(5):
                a = k * 2 * math.pi / 5 + self.rng.uniform(0, 1)
                px, py = x + math.cos(a) * s, y + math.sin(a) * s
                self.shape("ellipse", [(px - 0.7 * s, py - 0.7 * s), (px + 0.7 * s, py + 0.7 * s)], petal, 255)
            self.shape("ellipse", [(x - 0.5 * s, y - 0.5 * s), (x + 0.5 * s, y + 0.5 * s)], (214, 150, 40), 255)

    def rect(self, x_m, y_m, w_m, h_m, colour, height, edge=None):
        """A rectangle in metres from the square's corner (paths, slabs, beds), its edge darker."""
        x, y, w, h = self.m(x_m), self.m(y_m), self.m(w_m), self.m(h_m)
        self.shape("rectangle", [(x, y), (x + w, y + h)], _rgb(colour), height)
        if edge is not None:
            for a, b in (((x, y), (x + w, y)), ((x, y + h), (x + w, y + h)), ((x, y), (x, y + h)), ((x + w, y), (x + w, y + h))):
                self.shape("line", [a, b], _rgb(edge), height * 0.7, 2)

    def inside(self, rects_m):
        """A placement rule: within one of rects_m (x, y, w, h in metres)."""
        boxes = [tuple(self.m(v) for v in r) for r in rects_m]

        def rule(xs, ys):
            keep = np.zeros(len(xs), bool)
            for x, y, w, h in boxes:
                keep |= ((xs - x) % self.n < w) & ((ys - y) % self.n < h)
            return keep
        return rule

    def cobbles(self, stone_m, colours, joint, joint_m=0.012):
        """Cobbles without a direction: stones round a jittered grid (repeating), one colour each, domed, joints between."""
        n = max(2, round(self.metres / stone_m))
        cell = self.n / n
        jx, jy = self.rng.uniform(0.2, 0.8, (n, n)), self.rng.uniform(0.2, 0.8, (n, n))
        tint = self.rng.integers(0, len(colours), (n, n))
        shade = self.rng.uniform(0.9, 1.1, (n, n))
        yy, xx = np.mgrid[0:self.n, 0:self.n] + 0.5
        ci, cj = (xx // cell).astype(int), (yy // cell).astype(int)
        d1, d2, own = np.full(xx.shape, np.inf), np.full(xx.shape, np.inf), np.zeros(xx.shape, int)
        for di in (-1, 0, 1):
            for dj in (-1, 0, 1):
                i, j = ci + di, cj + dj
                d = np.hypot(xx - (i + jx[j % n, i % n]) * cell, yy - (j + jy[j % n, i % n]) * cell)
                closer = d < d1
                d2 = np.where(closer, d1, np.minimum(d2, d))
                own = np.where(closer, (j % n) * n + (i % n), own)
                d1 = np.where(closer, d, d1)
        gap = (d2 - d1) / 2
        dome = np.clip(gap / (0.5 * cell), 0, 1) ** 0.5
        col = np.asarray(colours, float)[tint.ravel()[own]] * (shade.ravel()[own] * (0.85 + 0.25 * dome))[..., None]
        grain = fbm(self.n, self.metres / 0.03, 2, self.rng)
        col *= (1 + 0.06 * grain)[..., None]
        joints = gap < self.m(joint_m)
        col[joints] = joint
        self.colour = Image.fromarray(np.clip(col, 0, 255).astype(np.uint8))
        self.height = Image.fromarray(np.where(joints, 20, 90 + 140 * dome).astype(np.uint8))
        self._draws()

    def rock(self, dark, light, layers=0, crack_m=0.6):
        """Rock: ridged noise for its relief and colour; layers: horizontal strata per square (a face)."""
        rng = self.rng
        ridged = 1 - np.abs(fbm(self.n, self.metres / crack_m, 5, rng))
        relief = ridged ** 2
        if layers:
            y = np.arange(self.n)[:, None] / self.n * layers + 0.25 * fbm(self.n, self.metres / 1.5, 2, rng)
            strata = 0.5 + 0.5 * np.sin(2 * math.pi * y)
            relief = 0.65 * relief + 0.35 * strata ** 3
        broad = 0.5 + 0.5 * fbm(self.n, self.metres / 2.0, 3, rng)
        shade = np.clip(0.55 * relief + 0.45 * broad, 0, 1)
        base = np.stack([np.interp(shade, [0, 1], [dark[k], light[k]]) for k in range(3)], -1)
        self.colour = Image.fromarray(np.clip(base, 0, 255).astype(np.uint8))
        self.height = Image.fromarray((relief * 230 + 10).astype(np.uint8))
        self.clumps = 2 * broad - 1
        self._draws()

    def finish(self):
        """Colour (RGB) and height (0..1) at px."""
        colour = self.colour.resize((self.px, self.px), Image.LANCZOS)
        height = self.height.resize((self.px, self.px), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.8))
        return colour, np.asarray(height, np.float32) / 255.0


# --- maps ---

def matched(colour, target):
    """colour with each channel scaled so its mean is target's: the build's colour and brightness, the detail kept. Pure."""
    a = np.asarray(colour, float)
    for _ in range(4):          # (again: what clips at 255, snow's highlights, pulls the mean back down)
        a = np.clip(a * np.asarray(target, float) / np.maximum(a.reshape(-1, 3).mean(0), 1), 0, 255)
    return Image.fromarray(a.round().astype(np.uint8))


def normal_map(height, strength):
    """+Y (OpenGL) normal map from a height field that repeats over its edges. Pure."""
    dx = (np.roll(height, -1, 1) - np.roll(height, 1, 1)) * strength
    dy = (np.roll(height, -1, 0) - np.roll(height, 1, 0)) * strength
    nx, ny, nz = -dx, dy, np.ones_like(height)
    length = np.sqrt(nx * nx + ny * ny + nz * nz)
    return Image.fromarray(np.stack([(c / length + 1) * 127.5 for c in (nx, ny, nz)], -1).round().astype(np.uint8))


def roughness_map(height, base, spread):
    """Roughness from base, lower on what stands up (tips, stones catch a soft highlight) by spread. Pure."""
    return Image.fromarray(np.clip(255 * (base - spread * height), 0, 255).astype(np.uint8))


def blend(a, b, mask):
    """(colour, height) a over b by mask (0..1, a where 1). Pure."""
    ca, ha = a
    cb, hb = b
    m = mask[..., None]
    colour = np.asarray(ca, float) * m + np.asarray(cb, float) * (1 - m)
    return Image.fromarray(np.clip(colour, 0, 255).astype(np.uint8)), ha * mask + hb * (1 - mask)


