// A racing kerb selected by two road clicks appears as an AC mesh and survives Save.
import {centre, expect, openEditor, scene, test} from "./fixtures";
import {meshes, picture, points, saveTrack, saved} from "./edit-helpers";

test("mark a kerb, adjust its physical profile, undo and save", async ({page, backend}) => {
  await backend.post("/__test/rebuild", {name: "alpha", title: "Alpha Test", hill: true, trees: false});
  await openEditor(page);
  const c = await centre(scene(page));
  await page.locator("#edit-kerb").click();
  const options = page.locator("#edit-kerb-options");
  await expect(options).toContainText("Racing kerb (B)");
  await expect(options).toContainText("road edge to start a kerb");
  await page.mouse.click(c.x, c.y + 236);
  await expect(options).toContainText("where this kerb ends");
  await page.mouse.click(c.x, c.y - 261);
  await expect(options.locator("#edit-kerb-delete")).toContainText("X");
  await expect(options.getByLabel("Select kerb")).toHaveCount(0);
  await expect(options.getByRole("button", {name: "New range"})).toHaveCount(0);
  await saved(page);
  const draft = await (await page.request.get("/api/editor/alpha/edits")).json();
  expect(draft.kerbs).toHaveLength(1);
  expect(draft.kerbs[0].line.length).toBeGreaterThan(10);
  expect(["left", "right"]).toContain(draft.kerbs[0].side);
  await expect(options.getByRole("button", {name: /Left edge|Right edge/})).toHaveCount(0);
  await expect(page.locator("#inspector-selection #inspect-appearance")).toBeVisible();
  await expect(page.locator("#inspector-selection #inspect-appearance img")).toBeVisible();
  await page.mouse.click(c.x, c.y + 236);
  await expect(options).toContainText("where this kerb ends");
  await page.locator("#edit-select").click();
  const withoutHighlight = await picture(page);
  let pickedKerb = false;
  let kerbPoint = {x: c.x, y: c.y};
  for (const y of [c.y, c.y - 100, c.y + 100]) {
    for (let dx = -150; dx <= 150; dx += 2) {
      await page.mouse.click(c.x + dx, y);
      if (await page.locator("#edit-select-kerb").count()) { pickedKerb = true; kerbPoint = {x: c.x + dx, y}; break; }
    }
    if (pickedKerb) break;
  }
  expect(pickedKerb, "clicking a kerb mesh should select its complete range").toBe(true);
  await expect(page.locator("#edit-select-kerb")).toContainText("B");
  await expect.poll(async () => (await picture(page)).equals(withoutHighlight)).toBe(false);
  const beforeSelect = await picture(page);
  const inspector = page.locator("#inspector-selection #inspect-kerb");
  await expect(inspector).toBeVisible();
  await expect(inspector.getByLabel("Kerb side")).toHaveCount(0);
  await expect(inspector.getByRole("button", {name: /Delete/})).toHaveCount(0);
  await expect(inspector.getByLabel("Kerb width")).toHaveValue("0.45");
  await expect(inspector.getByLabel("Kerb height")).toHaveValue("0.06");
  await expect(inspector.getByLabel("Kerb width")).toHaveAttribute("max", "2");
  await expect(inspector.getByLabel("Kerb height")).toHaveAttribute("max", "0.3");
  await expect(inspector.getByLabel("Kerb profile")).toHaveValue("rounded");
  await inspector.getByLabel("Kerb width").fill("0.5");
  await saved(page);
  expect((await (await page.request.get("/api/editor/alpha/edits")).json()).kerbs[0].width).toBe(0.5);
  await expect.poll(async () => (await picture(page)).equals(beforeSelect)).toBe(false);
  await page.locator("#edit-select-kerb").click();
  await expect(options.locator("#edit-kerb-delete")).toContainText("X");
  await expect(options.locator("kbd")).toHaveText(["Shift", "Ctrl", "Alt", "X"]);
  await page.mouse.move(c.x, c.y);
  await page.keyboard.down("Shift"); await page.mouse.wheel(0, -100); await page.keyboard.up("Shift");
  await expect(options.getByLabel("Width")).toHaveValue("0.55");
  await page.keyboard.down("Control"); await page.mouse.wheel(0, -100); await page.keyboard.up("Control");
  await expect(options.getByLabel("Height")).toHaveValue("0.07");
  await page.keyboard.down("Alt"); await page.mouse.wheel(0, -100); await page.keyboard.up("Alt");
  await expect(options.getByLabel("Kerb profile")).toHaveValue("ribbed");
  await page.keyboard.down("Alt"); await page.mouse.wheel(0, 100); await page.keyboard.up("Alt");
  await expect(options.getByLabel("Kerb profile")).toHaveValue("rounded");
  await page.locator("#edit-help").getByText("Help").click();
  await expect(page.locator("#edit-help")).toContainText("B");
  await expect(page.locator("#edit-help")).toContainText("complete range");
  await options.getByLabel("Height").fill("0.10");
  await options.getByLabel("Kerb profile").selectOption("ribbed");
  await saved(page);
  const changed = await (await page.request.get("/api/editor/alpha/edits")).json();
  expect(changed.kerbs[0].height).toBe(0.10);
  expect(changed.kerbs[0].profile).toBe("ribbed");
  await page.locator("#edit-history").getByRole("button", {name: "Undo"}).click();
  await expect(options.getByLabel("Kerb profile")).toHaveValue("rounded");
  await options.getByLabel("Width").fill("2");
  await options.getByLabel("Height").fill("0.30");
  await saved(page);
  const maximum = await (await page.request.get("/api/editor/alpha/edits")).json();
  expect(maximum.kerbs[0].width).toBe(2);
  expect(maximum.kerbs[0].height).toBe(0.3);
  await page.locator("#edit-select").click();
  await page.mouse.click(kerbPoint.x, kerbPoint.y);
  await expect(page.locator("#edit-select-delete")).toBeEnabled();
  await page.keyboard.press("x");
  await expect.poll(async () => (await (await page.request.get("/api/editor/alpha/edits")).json()).kerbs).toHaveLength(0);
  await page.keyboard.press("Control+z");
  await expect.poll(async () => (await (await page.request.get("/api/editor/alpha/edits")).json()).kerbs).toHaveLength(1);
  await points(page, kerbPoint);
  await page.mouse.click(kerbPoint.x, kerbPoint.y);
  await expect(page.locator("#edit-select-delete")).toBeEnabled();
  await page.keyboard.press("Delete");
  await expect.poll(async () => (await (await page.request.get("/api/editor/alpha/edits")).json()).kerbs).toHaveLength(0);
  await page.keyboard.press("Control+z");
  await expect.poll(async () => (await (await page.request.get("/api/editor/alpha/edits")).json()).kerbs).toHaveLength(1);
  await saveTrack(page);
  await expect.poll(async () => Object.keys(await meshes(page)).some(name => name.startsWith("1KERB_"))).toBe(true);
});
